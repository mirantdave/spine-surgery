export const ALL_STAVYA_STAFF_LIST: StavyaEmployee[] = Object.values(STAVYA_EMPLOYEES);

export function getEmployeesByUnit(unitName: string): StavyaEmployee[] {
  return ALL_STAVYA_STAFF_LIST.filter(emp => emp.unit.toLowerCase() === unitName.toLowerCase());
}

export function searchStavyaStaff(query: string): StavyaEmployee[] {
  const q = query.trim().toLowerCase();
  if (!q) return ALL_STAVYA_STAFF_LIST;
  return ALL_STAVYA_STAFF_LIST.filter(emp =>
    emp.name.toLowerCase().includes(q) ||
    emp.desig.toLowerCase().includes(q) ||
    emp.unit.toLowerCase().includes(q) ||
    emp.code.toLowerCase().includes(q) ||
    emp.dept_master.toLowerCase().includes(q) ||
    emp.mobile.includes(q)
  );
}

export function getDepartmentHead(unitName: string): StavyaEmployee | undefined {
  const headName = STAVYA_DEPARTMENT_HEADS[unitName];
  if (!headName) return undefined;
  return ALL_STAVYA_STAFF_LIST.find(e => e.name.toLowerCase() === headName.toLowerCase());
}
